#!/usr/bin/env python3
"""Generate runtime flavour and translation markers from reviewed, source-linked text."""
from pathlib import Path
import json, subprocess
ROOT=Path(__file__).resolve().parents[1]

def generate():
    pack=json.loads((ROOT/'content/narrative.json').read_text())
    rows=[]
    for entry in pack['entries']:
        label='narrative.'+entry['id'].lower().replace('-','_')
        rows.append('{id:'+json.dumps(entry['id'])+',source:'+json.dumps(entry['source'])+',name:'+json.dumps(entry['name'])+',contexts:'+json.dumps(entry['contexts'])+',label:N_('+json.dumps(label)+')}')
    code='// Generated by scripts/generate-narrative.py; reviewed source: content/narrative.json.\n'
    code+='const SOC_NARRATIVE=Object.freeze(['+','.join(rows)+'].map(e=>Object.freeze({...e,contexts:Object.freeze(e.contexts)})));\n'
    code+='const SOC_NARRATIVE_LABELS={title:N_("narrative.title"),scope:N_("narrative.scope")};\n'
    code+='function socNarrativeResource(kind){const e=SOC_NARRATIVE.find(e=>e.contexts.includes(kind));return e?`<p class="soc-flavour" data-narrative="${esc(e.id)}">${esc(tr(e.label))}</p>`:"";}\n'
    code+='function socNarrativePanel(){return `<details class="soc-business" id="soc-narrative"><summary>${tr(SOC_NARRATIVE_LABELS.title)}</summary><p>${tr(SOC_NARRATIVE_LABELS.scope)}</p>${SOC_NARRATIVE.map(e=>`<p data-narrative="${esc(e.id)}"><strong>${esc(e.name)}</strong> · ${esc(tr(e.label))}</p>`).join("")}</details>`;}\n'
    (ROOT/'src/game/88-narrative.js').write_text(code)
    labels={'narrative.'+e['id'].lower().replace('-','_'):e['text'] for e in pack['entries']}
    labels.update({'narrative.title':'Switchboard folklore','narrative.scope':'Fictional catalogue notes. Some products and scenarios are still in development; these descriptions do not establish service readiness.'})
    subprocess.run(['node','-e',"const D=require('./scripts/lib/dict'),fs=require('fs');const labels=JSON.parse(fs.readFileSync(0,'utf8'));for(const lang of ['en',...D.langs()]){const x=D.read(lang);for(const [k,v] of Object.entries(labels))if(lang==='en'||!(k in x.dict))x.dict[k]=v;D.write(lang,x.dict,x.header);}"],cwd=ROOT,input=json.dumps(labels),text=True,check=True)
    print('Generated '+str(len(rows))+' source-linked narrative adaptations with English fallback.')

if __name__=='__main__':generate()
